"""x0x/9W9 parameter tables only (the tanh table is the Prophet's); no samples."""
import math
import struct
import sys
from pathlib import Path

# 9W9's EXP pot ranges (er99_pots.h). One table per distinct (min, max).
EXP_RANGES = [
    ("BD_DECAY", 100.0, 4000.0), ("BD_PITCH", 0.43, 4.7), ("DRIVE", 0.85, 12.0),
    ("SD_TUNE", 130.0, 320.0), ("SD_TONE", 300.0, 4000.0),
    ("LT_TUNE", 50.0, 90.0), ("LT_DECAY", 80.0, 2600.0),
    ("MT_TUNE", 80.0, 125.0), ("MT_DECAY", 70.0, 2200.0),
    ("HT_TUNE", 110.0, 170.0), ("HT_DECAY", 60.0, 2000.0),
    ("RS_TUNE", 150.0, 300.0), ("CP_TUNE", 650.0, 1400.0), ("CP_TAIL", 120.0, 1000.0),
    ("OH_DECAY", 20.0, 1200.0), ("CH_DECAY", 15.0, 300.0), ("CY_DECAY", 100.0, 3000.0),
    ("SMP_PITCH", 0.25, 4.0),
]

TANH_N = 1024          # points over [0, TANH_MAX]; linear interpolation
TANH_MAX = 8.0


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def cfloat(x):
    s = repr(f32(x))
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def arr(ctype, name, vals, fmt=str, per=12):
    lines = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(fmt(v) for v in vals[i:i + per]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    out_t = Path(sys.argv[1] if len(sys.argv) > 1 else "build/gen/x0x_drum_tables.h")
    out_t.parent.mkdir(parents=True, exist_ok=True)
    t = ["/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/gen_909_tables.py; math tables only. */",
         "#pragma once", "",
         f"/* tanh(u) at u = i * {TANH_MAX} / {TANH_N}: Prophet's P5_TANH (melodee_tables.h, tanh(i / 128), in RAM) */",
         f"#define X0X_TANH_N {TANH_N}",
         f"#define X0X_TANH_SCALE {cfloat(TANH_N / TANH_MAX)}",
         "#define x0x_tanh_tab P5_TANH", "",
         "/* 9W9 EXP pots (er99_pots.h): value = min * (max/min)^(pot/127), pot 0..127, as min * 2^(log2(max/min) * pot/127)",
         " * (drum909.c d9_pot_value: fastmath.h fm_exp2f, rel 3e-7) */"]
    for i, (n, lo, hi) in enumerate(EXP_RANGES):
        t.append(f"#define X0X_EXP_{n} {i}   /* {lo:g} .. {hi:g} */")
    t.append(f"#define X0X_EXP_COUNT {len(EXP_RANGES)}")
    t.append(arr("float", "x0x_pot_lo", [f32(lo) for _, lo, _ in EXP_RANGES], cfloat, per=6))
    t.append(arr("float", "x0x_pot_l2", [f32(math.log2(f32(f32(hi) / f32(lo)))) for _, lo, hi in EXP_RANGES], cfloat, per=6))
    t.append("")
    out_t.write_text("\n".join(t))
    print(f"gen_909_tables: EXP pot ranges -> {out_t}")


if __name__ == "__main__":
    main()
