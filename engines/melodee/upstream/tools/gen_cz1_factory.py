"""CZ-1's factory tones: assets/cz1-factory/cz1-factory.syx (64 native CZ-1 tones, Casio's preset tones
A-1 .. H-8; tools/make_cz1_factory.py) -> a header for eng_cz.c:

  CZ_DICT[144], CZ_LZ_AT[65], CZ_LZ[]   the native tones (128 synthesis bytes + the 16-character LCD name), each
                        packed on its own (gen_tables.py lz_pack) against CZ_DICT, one of them, placed before it:
                        eng_cz.c cz_factory unpacks tone k from CZ_LZ + CZ_LZ_AT[k]
  CZ_SHORT[]            the PRESETS names (12 characters) that are not the LCD name stripped
Preset k + 1 is tone k: BANK A..D, PTCH 1..16 (cz_bank.c holds them as the default BANK A..D)

  tools/gen_cz1_factory.py OUT.h
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_tables import lz_pack, lz_unpack  # noqa: E402

SRC = Path(__file__).resolve().parent.parent / "assets/cz1-factory/cz1-factory.syx"
SHORT = {"FUNKY CLAVI.1": "FUNKY CLAV 1", "FUNKY CLAVI.2": "FUNKY CLAV 2", "AFRO-PERCUSSION": "AFRO PERC",
         "METALLIC SOUND": "METALLIC", "SYNTH.STRINGS": "SYN STRINGS", "SWEEP SOUND 1": "SWEEP 1",
         "SWEEP SOUND 2": "SWEEP 2", "SYNTH.DRUMS 1": "SYN DRUMS 1", "SYNTH.DRUMS 2": "SYN DRUMS 2",
         "TYPHOON SOUND": "TYPHOON"}
DICT = 45                          # the tone the others are packed against (the smallest total of 64 tried)


def valid(b):
    """cz_patch.h cz_patch_valid"""
    if (b[0] & 0xF0) or (b[0] >> 2) > 2 or b[1] > 1 or (b[2] & 3) or b[3] > 47:
        return False
    for off in (0, 57):
        if (b[16 + off] & 15) > 9 or (b[16 + off] >> 4) > 14 or b[18 + off] > 9:
            return False
    return not any(b[e] & 8 for e in (54, 37, 20, 111, 94, 77))


def tones():
    raw = SRC.read_bytes()
    if len(raw) != 64 * 296:
        raise SystemExit(f"{SRC}: {len(raw)} B, want 64 CZ-1 tone dumps of 296 B")
    out = []
    for k in range(64):
        m = raw[k * 296:(k + 1) * 296]
        if m[:6] != bytes([0xF0, 0x44, 0, 0, 0x70, 0x21]) or m[-1] != 0xF7 or any(x > 15 for x in m[7:-1]):
            raise SystemExit(f"{SRC}: tone {k + 1} is not a CZ-1 tone dump")
        t = bytes(m[7 + 2 * i] | m[8 + 2 * i] << 4 for i in range(144))
        if not valid(t) or not all(32 <= c <= 126 for c in t[128:]):
            raise SystemExit(f"{SRC}: tone {k + 1} is not a valid native tone")
        out.append(t)
    return out


def main(path):
    ts = tones()
    d = ts[DICT]
    packed = [lz_pack(d + x, len(d)) for x in ts]
    for x, c in zip(ts, packed):
        if lz_unpack(c, 144, d) != x:
            raise SystemExit("cz1 factory: packing does not round-trip")
    at = [0]
    for c in packed:
        at.append(at[-1] + len(c))
    data = b"".join(packed)
    short = []
    for k, x in enumerate(ts):
        name = x[128:].decode("ascii").strip()
        s = SHORT.get(name, name)
        if len(s) > 12:
            raise SystemExit(f"{name}: preset name over 12 characters")
        if s != name:
            short.append((k, s))
    rows = lambda v: ["    " + ",".join(map(str, v[i:i + 32])) + "," for i in range(0, len(v), 32)]
    L = ["/* generated by tools/gen_cz1_factory.py from assets/cz1-factory/cz1-factory.syx:",
         " * Casio's 64 CZ-1 preset tones (A-1 .. H-8), native 144-byte tones, packed (eng_cz.c cz_factory) */",
         f"#define CZ_FACTORY_N {len(ts)}u",
         "static const uint8_t CZ_DICT[144] = {"] + rows(list(d)) + ["};",
         f"static const uint16_t CZ_LZ_AT[{len(at)}] = {{"] + rows(at) + ["};",
         f"static const uint8_t CZ_LZ[{len(data)}] = {{"] + rows(list(data)) + ["};",
         "/* the PRESETS names that are not the tone's LCD name stripped */",
         f"static const struct {{ uint8_t k; char name[13]; }} CZ_SHORT[{len(short)}] = {{"]
    L += [f'    {{{k}, "{s}"}},' for k, s in short] + ["};"]
    Path(path).write_text("\n".join(L) + "\n")
    print(f"cz1 factory: {len(ts)} tones, {len(data) + 144 + 2 * len(at)} B packed -> {path}")

if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
